// Converts the Riot data already fetched by scripts/fetch-data.js into the
// numbers layer of the LoL content pack:
//
//   src/data/generated/*.json  ->  content/lol/generated/{units,perks}.yaml
//
// Only numbers are written here. Behaviour lives in content/lol/authored/ and
// refers to these numbers by id, so a balance patch is `npm run fetch-data`
// followed by `node tools/ingest/ingest.mjs`.

import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const src = join(root, 'src', 'data', 'generated');
const out = join(root, 'content', 'lol', 'generated');
const load = (name) => JSON.parse(readFileSync(join(src, name), 'utf8'));

const meta = load('meta.json');
const champions = load('champions.json');
const details = load('champion-details.json');
const items = load('items.json');
const itemBin = load('item-bin.json');

// "Blade of The Ruined King" -> "blade_of_the_ruined_king"
const slug = (s) =>
  s.toLowerCase().replace(/['’.]/g, '').replace(/[^a-z0-9]+/g, '_').replace(/^_|_$/g, '');
// "MoveSpeedMod" -> "move_speed_mod"
const snake = (s) => slug(s.replace(/([a-z0-9])([A-Z])/g, '$1_$2'));
const num = (n) => Number(Number(n).toFixed(6));

// Riot stat name -> [ruleset stat, scale].
const UNIT_STATS = {
  hp: ['max_hp', 1],
  mp: ['max_mana', 1],
  hpregen: ['hp_regen', 1],
  mpregen: ['mana_regen', 1],
  attackdamage: ['ad', 1],
  armor: ['armor', 1],
  spellblock: ['mr', 1],
  movespeed: ['move_speed', 1],
  attackrange: ['attack_range', 1],
};
const UNIT_GROWTH = {
  hpperlevel: ['max_hp', 1],
  mpperlevel: ['max_mana', 1],
  hpregenperlevel: ['hp_regen', 1],
  mpregenperlevel: ['mana_regen', 1],
  attackdamageperlevel: ['ad', 1],
  armorperlevel: ['armor', 1],
  spellblockperlevel: ['mr', 1],
  // Quoted in percent; the ruleset wants a fraction.
  attackspeedperlevel: ['attack_speed', 0.01],
};
const ITEM_STATS = {
  FlatHPPoolMod: 'max_hp',
  FlatMPPoolMod: 'max_mana',
  FlatPhysicalDamageMod: 'ad',
  FlatMagicDamageMod: 'ap',
  FlatArmorMod: 'armor',
  FlatSpellBlockMod: 'mr',
  FlatCritChanceMod: 'crit_chance',
  PercentAttackSpeedMod: 'attack_speed',
  PercentLifeStealMod: 'life_steal',
  FlatMovementSpeedMod: 'move_speed',
};
const DIRECT_STATS = { abilityHaste: 'ability_haste' };

const pick = (stats, table) => {
  const result = {};
  for (const [key, [name, scale]] of Object.entries(table)) {
    if (stats[key]) result[name] = num(stats[key] * scale);
  }
  return result;
};

const units = {};
for (const champ of champions) {
  const constants = {};
  for (const spell of details[champ.id]?.cdragon?.spells ?? []) {
    const ranks = spell.id === 'r' ? 3 : 5;
    constants[`${spell.id}_cooldown`] = (spell.cooldownCoefficients ?? []).slice(0, ranks).map(num);
    if (spell.range?.[0]) constants[`${spell.id}_range`] = num(spell.range[0]);
  }
  units[slug(champ.id)] = {
    stats: pick(champ.stats, UNIT_STATS),
    growth: pick(champ.stats, UNIT_GROWTH),
    params: { base_as: num(champ.stats.attackspeed) },
    constants,
  };
}

const perks = {};
for (const item of items) {
  const stats = {};
  for (const [key, name] of Object.entries(ITEM_STATS)) {
    if (item.stats?.[key]) stats[name] = num(item.stats[key]);
  }
  const bin = itemBin[item.id] ?? {};
  for (const [key, name] of Object.entries(DIRECT_STATS)) {
    if (bin.directStats?.[key]) stats[name] = num(bin.directStats[key]);
  }
  const constants = {};
  for (const [key, value] of Object.entries(bin.dataValues ?? {})) {
    if (typeof value === 'number') constants[snake(key)] = num(value);
  }
  const id = slug(item.name);
  // Several items share a name across game modes; keep the first (Summoner's Rift) one.
  if (!id || perks[id]) continue;
  perks[id] = { cost: item.gold ?? 0, stats, constants };
}

// The output is JSON, which is also valid YAML, with one entry per line for readable diffs.
const write = (file, data) => {
  const header =
    `# Generated by tools/ingest/ingest.mjs from Riot data, patch ${meta.version}.\n` +
    `# Do not edit by hand: authored files override these values where needed.\n`;
  const lines = Object.keys(data)
    .sort()
    .map((id) => `${JSON.stringify(id)}: ${JSON.stringify(data[id])}`);
  mkdirSync(out, { recursive: true });
  writeFileSync(join(out, file), `${header}${lines.join('\n')}\n`);
  console.log(`${file}: ${lines.length} entries`);
};

write('units.yaml', units);
write('perks.yaml', perks);
